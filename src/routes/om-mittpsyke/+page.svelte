<section class="container max-w-3xl mx-auto py-16 text-left">
	<h1 class="text-4xl font-bold tracking-tight mb-6 opacity-95">Om MittPsyke</h1>

	<p class="opacity-80 leading-relaxed mb-5">
		MittPsyke är en svensk plattform för digitalt samtalsstöd, skapad för människor som
		lever med psykisk belastning i olika former. Tanken är att erbjuda ett tryggt och
		tillgängligt rum där det går att stanna upp, sätta ord på det som känns svårt och få
		stöd i stunden, utan att behöva prestera eller förklara allt från början.
	</p>

	<p class="opacity-80 leading-relaxed mb-5">
		Plattformen fungerar som ett kompletterande stöd mellan, före eller efter kontakt med
		vården. I centrum finns ett AI-baserat samtalsstöd som är utformat för att svara med
		lugn, respekt och empati. Målet är inte att ersätta professionell behandling, utan att
		göra det lättare att reflektera, sortera tankar och vid behov hitta vidare till rätt
		resurser.
	</p>

	<p class="opacity-80 leading-relaxed mb-5">
		MittPsykes värdegrund bygger på integritet, frivillighet och mänsklig sårbarhet.
		Användaren ska kunna mötas utan dömande ton, utan krav på att må bättre snabbt och
		utan känslan av att bli reducerad till ett symptom. Varje steg ska kunna tas i egen
		takt.
	</p>

	<p class="opacity-80 leading-relaxed mb-4">
		För att skapa tydlighet är innehållet och stödet organiserat i tematiska ingångar:
	</p>
	<ul class="list-disc pl-5 space-y-2 opacity-80 leading-relaxed mb-5">
		<li>Ångest</li>
		<li>Depression</li>
		<li>Trauma & våld</li>
	</ul>

	<p class="opacity-80 leading-relaxed mb-5">
		De tematiska ingångarna gör det enklare att hitta ett sammanhang som känns relevant
		direkt. I stället för att navigera brett kan användaren börja där behovet är som störst
		och få stöd som känns mer träffsäkert och begripligt.
	</p>

	<p class="opacity-80 leading-relaxed mb-5">
		Designfilosofin är avskalad, mjuk och icke-klinisk. Gränssnittet är medvetet lugnt för
		att minska stress, undvika onödiga distraktioner och skapa en känsla av närvaro.
		Typografi, mellanrum och tonalitet är valda för att göra upplevelsen lättläst och
		omhändertagande.
	</p>

	<p class="opacity-80 leading-relaxed">
		MittPsyke kan användas anonymt för den som vill börja försiktigt. För den som önskar
		mer kontinuitet finns möjlighet till inloggning, där samtal kan sparas över tid och bli
		en personlig historik av reflektioner. På så sätt kan plattformen fungera som ett
		digitalt samtalsrum, och för vissa även som en personlig journal i vardagen.
	</p>
</section>
